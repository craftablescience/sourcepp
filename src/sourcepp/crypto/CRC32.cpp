uint32_t crypto::computeCRC32(std::span<const std::byte> buffer) {
	if (buffer.empty()) {
		return 0;
	}

	tomcrypt::crc32_state crc32;
	if (!tomcrypt::crc32_update(crc32, reinterpret_cast<const unsigned char*>(buffer.data()), buffer.size())) {
		return 0;
	}
	return tomcrypt::crc32_finish(crc32);
}
